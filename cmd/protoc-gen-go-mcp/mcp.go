package main

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/asjard/asjard/pkg/protobuf/mcpb"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
)

const (
	contextPackage = protogen.GoImportPath("context")
	jsonPackage    = protogen.GoImportPath("encoding/json")
	mcpPackage     = protogen.GoImportPath("github.com/asjard/asjard/pkg/server/mcp")
	serverPackage  = protogen.GoImportPath("github.com/asjard/asjard/core/server")
	// FileDescriptorProto.package field number
	fileDescriptorProtoPackageFieldNumber = 2
	// FileDescriptorProto.syntax field number
	fileDescriptorProtoSyntaxFieldNumber = 12
)

// McpGenerator generates MCP service descriptors and tool handlers.
type McpGenerator struct {
	plugin *protogen.Plugin
	gen    *protogen.GeneratedFile
	file   *protogen.File
}

// NewMcpGenerator creates a generator for one proto file.
func NewMcpGenerator(plugin *protogen.Plugin, file *protogen.File) *McpGenerator {
	return &McpGenerator{
		plugin: plugin,
		file:   file,
	}
}

// Run writes the generated MCP service file.
func (g *McpGenerator) Run() *protogen.GeneratedFile {
	if len(g.file.Services) == 0 {
		return nil
	}
	g.gen = g.plugin.NewGeneratedFile(g.file.GeneratedFilenamePrefix+"_mcp.pb.go", g.file.GoImportPath)

	g.genLeadingComments(g.file.Desc.SourceLocations().ByPath(protoreflect.SourcePath{fileDescriptorProtoSyntaxFieldNumber}))
	g.gen.P("// Code generated by ", name, ". DO NOT EDIT.")
	g.gen.P("// versions:")
	g.gen.P("// - ", name, " v", version)
	g.gen.P("// - protoc             ", g.protocVersion())
	if g.file.Proto.GetOptions().GetDeprecated() {
		g.gen.P("// ", g.file.Desc.Path(), " is a deprecated file.")
	} else {
		g.gen.P("// source: ", g.file.Desc.Path())
	}
	g.gen.P()

	g.genLeadingComments(g.file.Desc.SourceLocations().ByPath(protoreflect.SourcePath{fileDescriptorProtoPackageFieldNumber}))
	g.gen.P("package ", g.file.GoPackageName)
	g.gen.P()

	g.genFileContent()
	return g.gen
}

func (g *McpGenerator) genFileContent() {
	for _, service := range g.file.Services {
		g.genService(service)
	}
}

func (g *McpGenerator) genService(service *protogen.Service) {
	handlerNames := make([]string, 0, len(service.Methods))
	serverType := service.GoName + "Server"
	for _, method := range service.Methods {
		handlerNames = append(handlerNames, g.genServiceMethod(service, serverType, method))
	}
	g.genServiceDesc(service, serverType, handlerNames)
}

func (g *McpGenerator) genServiceMethod(service *protogen.Service, serverType string, method *protogen.Method) string {
	if !g.hasMcpOption(method) {
		return ""
	}
	hname := fmt.Sprintf("_%s_%s_McpHandler", service.GoName, method.GoName)
	g.genComment(method.Comments)
	g.gen.P("func ", hname, "(ctx ", contextPackage.Ident("Context"), ", req *", mcpPackage.Ident("CallToolRequest"), ", srv any, interceptor ", serverPackage.Ident("UnaryServerInterceptor"), ") (*", mcpPackage.Ident("CallToolResult"), ", error) {")
	g.gen.P("in := new(", method.Input.GoIdent, ")")
	g.gen.P("if err := ", mcpPackage.Ident("UnmarshalToolArguments"), "(req, in); err != nil {")
	g.gen.P("return ", mcpPackage.Ident("NewProtoToolResult"), "(nil, err)")
	g.gen.P("}")
	g.gen.P("if interceptor == nil {")
	g.gen.P("out, err := srv.(", serverType, ").", method.GoName, "(ctx, in)")
	g.gen.P("return ", mcpPackage.Ident("NewProtoToolResult"), "(out, err)")
	g.gen.P("}")
	g.gen.P("info := &", serverPackage.Ident("UnaryServerInfo"), "{")
	g.gen.P("Server: srv,")
	g.gen.P("FullMethod: ", service.GoName, "_", method.GoName, "_FullMethodName,")
	g.gen.P("Protocol: ", mcpPackage.Ident("Protocol"), ",")
	g.gen.P("}")
	g.gen.P("handler := func(ctx ", contextPackage.Ident("Context"), ", req any) (any, error) {")
	g.gen.P("return srv.(", serverType, ").", method.GoName, "(ctx, in)")
	g.gen.P("}")
	g.gen.P("resp, err := interceptor(ctx, in, info, handler)")
	g.gen.P("return ", mcpPackage.Ident("NewProtoToolResultFromAny"), "(resp, err)")
	g.gen.P("}")
	return hname
}

func (g *McpGenerator) genServiceDesc(service *protogen.Service, serverType string, handlerNames []string) {
	serviceDescVar := service.GoName + "McpServiceDesc"
	g.gen.P("// ", serviceDescVar, " is the ", mcpPackage.Ident("ServiceDesc"), " for ", service.GoName, " service.")
	g.gen.P("// It's only intended for direct use with ", mcpPackage.Ident("AddHandler"), ",")
	g.gen.P("// and not to be introspected or modified (even as a copy)")
	g.genComment(service.Comments)
	g.gen.P("var ", serviceDescVar, " = ", mcpPackage.Ident("ServiceDesc"), " {")
	serviceName := g.getCommentTitle(service.Comments)
	if serviceName == "" {
		fullNames := strings.Split(string(service.Desc.FullName()), ".")
		if len(fullNames) > 0 {
			serviceName = fullNames[len(fullNames)-1]
		}
	}
	g.gen.P("Name: ", strconv.Quote(serviceName), ",")
	g.gen.P("ServiceName: ", strconv.Quote(string(service.Desc.FullName())), ",")
	g.gen.P("Desc: ", strconv.Quote(g.getCommentOneLine(service.Comments)), ",")
	g.gen.P("HandlerType: (*", serverType, ")(nil),")
	g.gen.P("Tools: []", mcpPackage.Ident("ToolDesc"), "{")
	for i, method := range service.Methods {
		if handlerNames[i] == "" {
			continue
		}
		g.genToolDesc(service, method, handlerNames[i])
	}
	g.gen.P("},")
	g.gen.P("}")
	g.gen.P()
}

func (g *McpGenerator) genToolDesc(service *protogen.Service, method *protogen.Method, handlerName string) {
	g.gen.P("{")
	g.gen.P("Name: ", service.GoName, "_", method.GoName, "_FullMethodName,")
	g.gen.P("Title: ", strconv.Quote(g.getCommentTitle(method.Comments)), ",")
	g.gen.P("Description: ", strconv.Quote(g.getCommentDesc(method.Comments)), ",")
	g.gen.P("InputSchema: ", jsonPackage.Ident("RawMessage"), "(", strconv.Quote(messageSchema(method.Input, true)), "),")
	g.gen.P("OutputSchema: ", jsonPackage.Ident("RawMessage"), "(", strconv.Quote(messageSchema(method.Output, false)), "),")
	g.gen.P("Handler: ", handlerName, ",")
	g.gen.P("},")
}

func (g *McpGenerator) hasMcpOption(method *protogen.Method) bool {
	if method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer() {
		return false
	}
	tool, ok := proto.GetExtension(method.Desc.Options(), mcpb.E_McpTool).(*mcpb.McpTool)
	return ok && tool != nil
}

func (g *McpGenerator) genLeadingComments(loc protoreflect.SourceLocation) {
	for _, s := range loc.LeadingDetachedComments {
		g.gen.P(protogen.Comments(s))
		g.gen.P()
	}
	if s := loc.LeadingComments; s != "" {
		g.gen.P(protogen.Comments(s))
		g.gen.P()
	}
}

func (g *McpGenerator) genComment(comments protogen.CommentSet) {
	if comments.Leading != "" {
		g.gen.P(strings.TrimSpace(comments.Leading.String()))
	}
	if comments.Trailing != "" {
		g.gen.P(strings.TrimSpace(comments.Trailing.String()))
	}
}

func (g *McpGenerator) getCommentOneLine(commentSet protogen.CommentSet) string {
	commentStr := ""
	if commentSet.Leading != "" {
		commentStr += strings.TrimSpace(commentSet.Leading.String())
	}
	if commentSet.Trailing != "" {
		commentStr += strings.TrimSpace(commentSet.Trailing.String())
	}

	sb := strings.Builder{}
	commentLines := strings.Split(strings.TrimSuffix(commentStr, "\n"), "\n")
	commentLinesLen := len(commentLines)
	for index, line := range commentLines {
		sb.WriteString(strings.TrimPrefix(line, "//"))
		if index == commentLinesLen-1 {
			sb.WriteString(".")
		} else {
			sb.WriteString(",")
		}
	}
	return strings.TrimSpace(sb.String())
}

func (g *McpGenerator) getCommentDesc(commentSet protogen.CommentSet) string {
	title := g.getCommentTitle(commentSet)
	if title == "" {
		return ""
	}
	lines := make([]string, 0)
	if commentSet.Leading != "" {
		for _, line := range strings.Split(strings.TrimSuffix(strings.TrimSpace(commentSet.Leading.String()), "\n"), "\n") {
			line = strings.TrimSpace(strings.TrimPrefix(line, "//"))
			if line != "" {
				lines = append(lines, line)
			}
		}
	}
	if commentSet.Trailing != "" {
		line := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(commentSet.Trailing.String()), "//"))
		if line != "" {
			lines = append(lines, line)
		}
	}
	if len(lines) <= 1 {
		return title
	}
	return strings.Join(lines[1:], "\n")
}

func (g *McpGenerator) getCommentTitle(commentSet protogen.CommentSet) string {
	if commentSet.Leading != "" {
		lines := strings.Split(strings.TrimSuffix(strings.TrimSpace(commentSet.Leading.String()), "\n"), "\n")
		if len(lines) != 0 {
			return strings.TrimSpace(strings.TrimPrefix(lines[0], "//"))
		}
	}
	if commentSet.Trailing != "" {
		return strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(commentSet.Trailing.String()), "//"))
	}
	return ""
}

func (g *McpGenerator) protocVersion() string {
	v := g.plugin.Request.GetCompilerVersion()
	if v == nil {
		return "(unknown)"
	}
	var suffix string
	if s := v.GetSuffix(); s != "" {
		suffix = "-" + s
	}
	return fmt.Sprintf("v%d.%d.%d%s", v.GetMajor(), v.GetMinor(), v.GetPatch(), suffix)
}
